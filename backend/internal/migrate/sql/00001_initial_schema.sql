-- Full initial schema. This is a single squashed migration: there is no
-- production database to preserve, so the whole schema stands up in one file
-- rather than a chain of incremental migrations. Tables are ordered by FK
-- dependency (printers before the menu tables that reference them).

-- Tenants own locations; locations own devices; orders are stamped with
-- (tenant_id, location_id) at ingest. The composite-FK trick on
-- (location_id, tenant_id) is what enforces "two tenants cannot overlap a
-- location" — a location's tenant is single-valued, and devices/orders can
-- only reference a location through its owning tenant.
--
-- config: tenant-wide free-form jsonb (dark mode, locale, currency defaults).
-- username/password_hash: optional store-manager login (one restaurant = one
-- tenant). Nullable — tenants without creds can't log in via /store/v1/login
-- until set. password_hash reuses the SHA-256 hashing used for device keys
-- (authSvc.HashKey) — see internal/app/tenancy/service.go.
CREATE TABLE tenants (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    slug          text        NOT NULL UNIQUE,
    name          text        NOT NULL,
    config        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    username      text,
    password_hash text,
    created_at    timestamptz NOT NULL DEFAULT now()
);
-- Usernames are unique when present; multiple NULLs are allowed.
CREATE UNIQUE INDEX idx_tenants_username ON tenants (username) WHERE username IS NOT NULL;

-- Location identity + config. Address/phone are first-class columns because
-- they're structurally fundamental to a physical store; everything else
-- (tax_rate_bps, receipt_footer, …) goes into the jsonb config blob.
-- store_type: grocery-ready discriminator; every location is a restaurant today.
CREATE TABLE locations (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id         uuid        NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
    slug              text        NOT NULL,
    name              text        NOT NULL,
    timezone          text        NOT NULL DEFAULT 'America/New_York',
    -- daily_reset_hour: hour [0..23] in `timezone` at which kitchen_order_number
    -- resets. Reserved column — the reset logic is not implemented yet.
    daily_reset_hour  smallint    NOT NULL DEFAULT 0,
    phone             text        NOT NULL DEFAULT '',
    address_line1     text        NOT NULL DEFAULT '',
    address_line2     text        NOT NULL DEFAULT '',
    config            jsonb       NOT NULL DEFAULT '{}'::jsonb,
    store_type        text        NOT NULL DEFAULT 'restaurant',
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, slug),
    -- composite uniqueness so child rows can FK on (location_id, tenant_id)
    UNIQUE (id, tenant_id)
);
CREATE INDEX idx_locations_tenant ON locations(tenant_id);

-- Printers are scoped to a location. Composite FK keeps them honest under the
-- same "two tenants cannot overlap a location" invariant as devices.
-- (location_id, name) UNIQUE prevents two printers sharing a name within one
-- store (menu printer assignments + routing rely on names being unique).
CREATE TABLE printers (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id   uuid        NOT NULL,
    location_id uuid        NOT NULL,
    name        text        NOT NULL,
    ip          text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id) ON DELETE CASCADE,
    UNIQUE (location_id, name)
);
CREATE INDEX idx_printers_location ON printers(location_id);

-- A "device" is anything that authenticates with an API key: an agent, the
-- mobile app, a future direct-ingest endpoint. Cleartext key is shown to the
-- operator at mint time and never stored — only the SHA-256 lives in
-- key_hash. key_prefix is a non-secret short prefix shown in the UI so
-- operators can identify keys without revealing the secret.
CREATE TABLE devices (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id     uuid        NOT NULL,
    location_id   uuid        NOT NULL,
    name          text        NOT NULL,
    kind          text        NOT NULL DEFAULT 'agent',
    key_hash      text        NOT NULL UNIQUE,
    key_prefix    text        NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_used_at  timestamptz,
    revoked_at    timestamptz,
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id) ON DELETE RESTRICT
);
CREATE INDEX idx_devices_active ON devices(key_hash) WHERE revoked_at IS NULL;
CREATE INDEX idx_devices_location ON devices(location_id);

-- Orders. Identity is the canonical UUIDv7 generated by main/. Source
-- attribution (where it came from) lives in (source, source_event_id);
-- (tenant_id, source, source_event_id) is the dedupe key so two tenants
-- happening to share a vendor order number do not collide.
--
-- kitchen_order_number: reserved column. Will hold a per-location daily-
-- resetting counter shown on receipts. Not assigned yet — left nullable.
CREATE TABLE orders (
    id                    uuid        PRIMARY KEY,
    tenant_id             uuid        NOT NULL,
    location_id           uuid        NOT NULL,
    schema_version        integer     NOT NULL DEFAULT 1,
    source                text        NOT NULL,
    source_event_id       text        NOT NULL,
    kitchen_order_number  integer,
    status                text        NOT NULL,
    source_status         text        NOT NULL DEFAULT '',
    currency              text        NOT NULL,

    subtotal_cents        bigint      NOT NULL,
    tax_cents             bigint      NOT NULL,
    tip_cents             bigint      NOT NULL,
    total_cents           bigint      NOT NULL,
    fees                  jsonb       NOT NULL DEFAULT '[]'::jsonb,
    discounts             jsonb       NOT NULL DEFAULT '[]'::jsonb,

    customer_display_name text        NOT NULL DEFAULT '',
    customer_email        text        NOT NULL DEFAULT '',
    customer_phone        text        NOT NULL DEFAULT '',
    customer_external_id  text        NOT NULL DEFAULT '',

    fulfillment_type      text        NOT NULL,
    fulfillment_address   jsonb,
    promised_at           timestamptz,
    table_id              text        NOT NULL DEFAULT '',

    notes                 text        NOT NULL DEFAULT '',
    source_metadata       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    raw_payload           bytea       NOT NULL,

    placed_at             timestamptz NOT NULL,
    received_at           timestamptz NOT NULL,
    updated_at            timestamptz NOT NULL,

    UNIQUE (tenant_id, source, source_event_id),
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id) ON DELETE RESTRICT
);
CREATE INDEX idx_orders_received_at ON orders(received_at DESC);
CREATE INDEX idx_orders_location_received ON orders(location_id, received_at DESC);

CREATE TABLE line_items (
    id                uuid     PRIMARY KEY,
    order_id          uuid     NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    parent_id         uuid              REFERENCES line_items(id) ON DELETE CASCADE,
    position          integer  NOT NULL,
    sku               text     NOT NULL DEFAULT '',
    name              text     NOT NULL,
    quantity          integer  NOT NULL,
    unit_price_cents  bigint   NOT NULL,
    line_total_cents  bigint   NOT NULL,
    notes             text     NOT NULL DEFAULT ''
);
CREATE INDEX idx_line_items_order_id ON line_items(order_id);
CREATE INDEX idx_line_items_parent_id ON line_items(parent_id);

CREATE TABLE payments (
    id            uuid        PRIMARY KEY,
    order_id      uuid        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    processor     text        NOT NULL,
    status        text        NOT NULL,
    amount_cents  bigint      NOT NULL,
    token         text        NOT NULL DEFAULT '',
    last4         text        NOT NULL DEFAULT '',
    captured_at   timestamptz
);
CREATE INDEX idx_payments_order_id ON payments(order_id);

CREATE TABLE status_events (
    order_id    uuid        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    position    integer     NOT NULL,
    from_status text        NOT NULL DEFAULT '',
    to_status   text        NOT NULL,
    at          timestamptz NOT NULL,
    actor       text        NOT NULL,
    actor_id    uuid,
    reason      text        NOT NULL DEFAULT '',
    PRIMARY KEY (order_id, position)
);

-- Outbox: events carry (tenant_id, location_id) so future routing /
-- per-scope back-pressure decisions don't require parsing the payload.
CREATE TABLE outbox_events (
    id              uuid        PRIMARY KEY,
    aggregate_id    uuid        NOT NULL,
    tenant_id       uuid        NOT NULL,
    location_id     uuid        NOT NULL,
    type            text        NOT NULL,
    payload         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    occurred_at     timestamptz NOT NULL,
    schema_version  integer     NOT NULL DEFAULT 1
);
CREATE INDEX idx_outbox_events_occurred_at ON outbox_events(occurred_at);
CREATE INDEX idx_outbox_events_aggregate_id ON outbox_events(aggregate_id);
CREATE INDEX idx_outbox_events_scope ON outbox_events(tenant_id, location_id);

CREATE TABLE outbox_dispatches (
    event_id         uuid        NOT NULL REFERENCES outbox_events(id) ON DELETE CASCADE,
    handler_name     text        NOT NULL,
    dispatched_at    timestamptz,
    attempts         integer     NOT NULL DEFAULT 0,
    last_error       text        NOT NULL DEFAULT '',
    last_attempt_at  timestamptz,
    next_attempt_at  timestamptz,
    PRIMARY KEY (event_id, handler_name)
);
CREATE INDEX idx_outbox_dispatches_pending
    ON outbox_dispatches (handler_name, next_attempt_at NULLS FIRST)
    WHERE dispatched_at IS NULL;

-- ─── Menu module (per-location catalog) ─────────────────────────────────────

-- A location has one or more named menus (day-part hours are a later concern).
CREATE TABLE menus (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id   uuid        NOT NULL,
    location_id uuid        NOT NULL,
    name        text        NOT NULL,
    description text        NOT NULL DEFAULT '',
    available   boolean     NOT NULL DEFAULT true,
    position    integer     NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id) ON DELETE CASCADE,
    UNIQUE (id, tenant_id)
);
CREATE INDEX idx_menus_location ON menus(location_id);

CREATE TABLE menu_categories (
    id                 uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id          uuid        NOT NULL,
    location_id        uuid        NOT NULL,
    menu_id            uuid        NOT NULL,
    name               text        NOT NULL,
    description        text        NOT NULL DEFAULT '',
    available          boolean     NOT NULL DEFAULT true,
    position           integer     NOT NULL DEFAULT 0,
    default_printer_id uuid,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (menu_id, tenant_id)     REFERENCES menus(id, tenant_id)      ON DELETE CASCADE,
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id)  ON DELETE CASCADE,
    FOREIGN KEY (default_printer_id)     REFERENCES printers(id)              ON DELETE SET NULL,
    UNIQUE (id, tenant_id)
);
CREATE INDEX idx_menu_categories_menu ON menu_categories(menu_id);

CREATE TABLE menu_items (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id     uuid        NOT NULL,
    location_id   uuid        NOT NULL,
    category_id   uuid        NOT NULL,
    name          text        NOT NULL,
    description   text        NOT NULL DEFAULT '',
    price_cents   bigint      NOT NULL DEFAULT 0,          -- mirrors order.Money
    tax_rate_bps  integer     NOT NULL DEFAULT 0,          -- basis points (600 = 6.00%)
    in_stock      boolean     NOT NULL DEFAULT true,
    out_until     timestamptz,                             -- snooze; auto-back-in-stock past this
    tags          jsonb       NOT NULL DEFAULT '[]'::jsonb,-- food-label tags
    printer_id    uuid,                                    -- assigned printer (else category default)
    position      integer     NOT NULL DEFAULT 0,
    attributes    jsonb       NOT NULL DEFAULT '{}'::jsonb,-- grocery-ready (barcode/qty/unit later)
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (category_id, tenant_id) REFERENCES menu_categories(id, tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id)       ON DELETE CASCADE,
    FOREIGN KEY (printer_id)             REFERENCES printers(id)                   ON DELETE SET NULL,
    UNIQUE (id, tenant_id)
);
CREATE INDEX idx_menu_items_category ON menu_items(category_id);

-- Reusable modifier groups (attached to items many-to-many).
CREATE TABLE modifier_groups (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id      uuid        NOT NULL,
    location_id    uuid        NOT NULL,
    name           text        NOT NULL,
    required       boolean     NOT NULL DEFAULT false,
    min_select     integer     NOT NULL DEFAULT 0,
    max_select     integer     NOT NULL DEFAULT 0,          -- 0 = unlimited
    allow_multiple boolean     NOT NULL DEFAULT false,      -- repeat the same option
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id) ON DELETE CASCADE,
    UNIQUE (id, tenant_id)
);
CREATE INDEX idx_modifier_groups_location ON modifier_groups(location_id);

CREATE TABLE modifier_options (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id         uuid        NOT NULL,
    location_id       uuid        NOT NULL,
    group_id          uuid        NOT NULL,
    name              text        NOT NULL,
    price_delta_cents bigint      NOT NULL DEFAULT 0,        -- mirrors order.Money
    in_stock          boolean     NOT NULL DEFAULT true,
    position          integer     NOT NULL DEFAULT 0,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (group_id, tenant_id) REFERENCES modifier_groups(id, tenant_id) ON DELETE CASCADE,
    UNIQUE (id, tenant_id)
);
CREATE INDEX idx_modifier_options_group ON modifier_options(group_id);

CREATE TABLE item_modifier_groups (
    tenant_id uuid    NOT NULL,
    item_id   uuid    NOT NULL,
    group_id  uuid    NOT NULL,
    position  integer NOT NULL DEFAULT 0,
    FOREIGN KEY (item_id, tenant_id)  REFERENCES menu_items(id, tenant_id)      ON DELETE CASCADE,
    FOREIGN KEY (group_id, tenant_id) REFERENCES modifier_groups(id, tenant_id) ON DELETE CASCADE,
    PRIMARY KEY (item_id, group_id)
);
CREATE INDEX idx_item_modifier_groups_group ON item_modifier_groups(group_id);

-- ─── Operators (call-center order-takers; read-only menu access) ────────────

-- Operators are call-center order-takers (deliberately NOT "agent" — that's the
-- Pi printer bridge). They log in for a read-only bearer token that authorizes
-- reading menus for their allowed locations.
CREATE TABLE operators (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    username      text        NOT NULL UNIQUE,
    password_hash text        NOT NULL,
    display_name  text        NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE operator_locations (
    operator_id uuid NOT NULL REFERENCES operators(id) ON DELETE CASCADE,
    tenant_id   uuid NOT NULL,
    location_id uuid NOT NULL,
    FOREIGN KEY (location_id, tenant_id) REFERENCES locations(id, tenant_id) ON DELETE CASCADE,
    PRIMARY KEY (operator_id, location_id)
);
CREATE INDEX idx_operator_locations_op ON operator_locations(operator_id);

CREATE TABLE operator_tokens (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    operator_id  uuid        NOT NULL REFERENCES operators(id) ON DELETE CASCADE,
    token_hash   text        NOT NULL UNIQUE,
    token_prefix text        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    expires_at   timestamptz,
    revoked_at   timestamptz
);
CREATE INDEX idx_operator_tokens_hash ON operator_tokens(token_hash);

