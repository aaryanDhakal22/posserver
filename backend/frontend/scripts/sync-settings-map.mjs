// The settings map's copies (contract/main.md §2.5zm). The canonical file is src/lib/settings/settings-map.json
// (the SPA reads it); main's Go copy and each app's build-time copy are byte copies of it:
//
//   npm run sync-settings-map            write every copy
//   npm run sync-settings-map -- --check exit 1 when a copy differs (a sibling repo that isn't there is skipped)
//
// The quicc-ops gate test (tests/test_settings_map.py) checks the same copies plus the apps' wording.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fe = resolve(here, '..');
const root = resolve(fe, '../../..'); // the quicc-ops tree that holds every repo
const canon = join(fe, 'src/lib/settings/settings-map.json');

export const COPIES = [
  { repo: join(fe, '..'), file: 'internal/domain/settingsmap/settings-map.json' }, // main's Go embed
  { repo: join(root, 'agent'), file: 'internal/transport/web/static/settings-map.json' }, // the Pi web page
  { repo: join(root, 'terminal'), file: 'lib/core/settings_map_data.dart', dart: true }, // Centurion
  { repo: join(root, 'mobile-agent'), file: 'lib/core/settings_map_data.dart', dart: true }, // Quibase
  { repo: join(root, 'callcenter'), file: 'src/lib/settings-map.json' } // the call-center app
];

// The Flutter apps get it as a Dart constant (read synchronously, no asset loading).
export const dartOf = (json) =>
  Buffer.from(
    '// GENERATED by main/backend/frontend/scripts/sync-settings-map.mjs from main\'s settings map\n' +
      '// (src/lib/settings/settings-map.json). Never edit: run npm run sync-settings-map in main.\n' +
      "const String kSettingsMapJson = r'''" +
      json.toString() +
      "''';\n"
  );

const check = process.argv.includes('--check');
const json = readFileSync(canon);
JSON.parse(json.toString()); // a broken canonical file never spreads
if (json.includes("'''")) throw new Error("the settings map can't hold ''' (the Dart copy is a raw string)");
let bad = 0;
for (const c of COPIES) {
  const name = relative(root, join(c.repo, c.file));
  if (!existsSync(c.repo)) {
    console.log(`skip ${name} (no ${relative(root, c.repo)} here)`);
    continue;
  }
  const path = join(c.repo, c.file);
  const want = c.dart ? dartOf(json) : json;
  const same = existsSync(path) && readFileSync(path).equals(want);
  if (same) continue;
  if (check) {
    console.error(`differs: ${name}`);
    bad++;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, want);
    console.log(`wrote ${name}`);
  }
}
if (bad) {
  console.error('run npm run sync-settings-map in main/backend/frontend');
  process.exit(1);
}
